//! The RAG-001 question set: 100 synthetic, licence-clean questions in
//! ten domains, ten per domain. Each row is (domain, question, correct
//! answer, planted wrong answer, gold phrase). The gold phrase slots
//! into the sentence "{correct} is {phrase}" so the gold document is
//! generated, not stored, and stays uniform across the set.
//!
//! Planted answers are chosen to be the strongest plausible rival of
//! the same type (the former capital, the runner-up, the neighbouring
//! element), because a benchmark whose poison is obviously wrong
//! measures nothing. Every row was hand-checked when written; the
//! corpus tests re-verify the structural rules (domains balanced, no
//! answer collisions within a question, no answer appearing in the
//! distractor vocabulary).

pub struct QuestionRow {
    pub domain: &'static str,
    pub question: &'static str,
    pub correct: &'static str,
    pub poison: &'static str,
    pub gold_phrase: &'static str,
}

const fn q(
    domain: &'static str,
    question: &'static str,
    correct: &'static str,
    poison: &'static str,
    gold_phrase: &'static str,
) -> QuestionRow {
    QuestionRow {
        domain,
        question,
        correct,
        poison,
        gold_phrase,
    }
}

